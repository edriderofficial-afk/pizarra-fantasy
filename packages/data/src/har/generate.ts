import { inferShape, mergeShapes, renderZod, type Shape } from './infer';
import type { HarEntry } from './parse';
import { schemaName, templatePath } from './paths';

export interface EndpointSummary {
  readonly method: string;
  readonly host: string;
  readonly path: string;
  readonly schemaName: string;
  readonly samples: number;
  readonly statuses: readonly number[];
  /** true if at least one successful sample was obtained WITHOUT credentials (strategy A). */
  readonly worksWithoutAuth: boolean;
  readonly queryParams: readonly string[];
}

export interface GenerationResult {
  readonly endpoints: readonly EndpointSummary[];
  /** TypeScript source with one Zod schema per endpoint (2xx responses). */
  readonly schemasSource: string;
}

export function generate(entries: readonly HarEntry[]): GenerationResult {
  const groups = new Map<string, { entries: HarEntry[]; shape: Shape | null; template: string }>();
  for (const e of entries) {
    const template = templatePath(e.path);
    const key = `${e.method} ${e.host}${template}`;
    const g = groups.get(key) ?? { entries: [], shape: null, template };
    g.entries.push(e);
    if (e.status >= 200 && e.status < 300) g.shape = mergeShapes(g.shape, inferShape(e.json));
    groups.set(key, g);
  }
  const summaries: EndpointSummary[] = [];
  const blocks: string[] = [];
  const used = new Set<string>();
  for (const [, g] of [...groups.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    const first = g.entries[0] as HarEntry;
    let name = `${schemaName(first.method, g.template)}Response`;
    for (let i = 2; used.has(name); i++)
      name = `${schemaName(first.method, g.template)}Response${i}`;
    used.add(name);
    summaries.push({
      method: first.method,
      host: first.host,
      path: g.template,
      schemaName: name,
      samples: g.entries.length,
      statuses: [...new Set(g.entries.map((e) => e.status))].sort((a, b) => a - b),
      worksWithoutAuth: g.entries.some(
        (e) => !e.hadCredentials && e.status >= 200 && e.status < 300,
      ),
      queryParams: [...new Set(g.entries.flatMap((e) => Object.keys(e.query)))].sort(),
    });
    if (g.shape) {
      blocks.push(
        `/** ${first.method} ${first.host}${g.template} (${g.entries.length} samples) */\nexport const ${name} = ${renderZod(g.shape)};\n`,
      );
    }
  }
  const schemasSource = [
    '// AUTO-GENERATED by scripts/har-to-types.ts from a sanitized HAR. Do not edit by hand.',
    "import { z } from 'zod';",
    '',
    ...blocks,
  ].join('\n');
  return { endpoints: summaries, schemasSource };
}
